import test from 'node:test';
import assert from 'node:assert/strict';
import { defaultRange } from './params';

/**
 * Период по умолчанию. Радар открывают каждый день, и почти всегда смотрят
 * текущий месяц — он и должен быть выбран сам.
 */

const AUGUST = ['2026-08-19', '2026-08-25', '2026-08-31'];
const SEPTEMBER = ['2026-09-01', '2026-09-02', '2026-09-04'];

test('открывается текущий месяц, а не весь загруженный период', () => {
  const r = defaultRange([...AUGUST, ...SEPTEMBER], '2026-09-04');

  assert.deepEqual(r, { from: '2026-09-01', to: '2026-09-04' });
});

test('наступил новый месяц — радар сам переключается на него', () => {
  // Ровно то, ради чего это делалось: 1 октября открывается октябрь.
  const dates = [...SEPTEMBER, '2026-10-01'];

  assert.deepEqual(defaultRange(dates, '2026-09-30'), { from: '2026-09-01', to: '2026-09-04' });
  assert.deepEqual(defaultRange(dates, '2026-10-01'), { from: '2026-10-01', to: '2026-10-01' });
});

test('границы берутся по дням с данными, а не по календарю', () => {
  // Иначе период тянулся бы до 30-го числа по пустым дням.
  const r = defaultRange(['2026-09-03', '2026-09-04'], '2026-09-15');

  assert.equal(r.from, '2026-09-03', 'не 2026-09-01');
  assert.equal(r.to, '2026-09-04', 'не 2026-09-30');
});

test('в новом месяце данных ещё нет — показываем последний месяц с данными', () => {
  // Первое число, выгрузку не залили: пустой экран выглядел бы поломкой.
  const r = defaultRange([...AUGUST, ...SEPTEMBER], '2026-10-01');

  assert.deepEqual(r, { from: '2026-09-01', to: '2026-09-04' });
});

test('данных нет вовсе — берём сегодняшний день, а не падаем', () => {
  assert.deepEqual(defaultRange([], '2026-09-04'), { from: '2026-09-04', to: '2026-09-04' });
});
