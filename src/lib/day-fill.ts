/**
 * С какого дня витрину меряют ещё и в 18:30. До него замеров два, и пустое
 * 18:30 за прошлые дни — не пропуск: его тогда просто не было. По этой дате
 * редактор решает, показывать ли поле, а отчёт «Кто не заполнил» — с какого
 * дня спрашивать замер.
 */
export const EVENING_FROM = '2026-10-26';

/** Меряют ли витрину в 18:30 в этот день. */
export function hasEvening(date: string): boolean {
  return date >= EVENING_FROM;
}

/**
 * Итог дня по витрине — среднее замеров: утром, в 16:00 и (с 26.10.2026) в 18:30.
 *
 * Отдельный модуль без зависимостей: формулу зовут и сервер (dayFill в
 * showcase-store.ts — радар, сводка, балл, Excel), и редактор в браузере
 * (превью статуса, пока правка летит на сервер). Две копии одной формулы
 * однажды разъехались бы, и статус в строке мигал бы при сохранении.
 *
 * До 06.10.2026 итогом был худший из двух замеров; заказчик перевёл его на
 * среднее — то же, что в столбце «Средний результат» выгрузки в Excel.
 *
 * Сюда приходят только заполненные замеры. Незаполненный в среднее не
 * входит: не мерили в 16:00 — итог и есть утренний замер, как есть, а не его
 * половина; это решают вызывающие (dayFill, dayStatusOf).
 *
 * Каждый замер — целый процент (так он и хранится), среднее тоже округляется
 * до целого, половинка вверх: 95% и 94% дают 95%. Пороги витрины целые (🟢 от
 * 95%, 🟡 от 85%), и без округления 94,5% показывались бы как «95%» с жёлтым
 * статусом. Считаем в целых процентах: (0.95 + 0.94) / 2 в долях даёт
 * 0.9449999…, и половинка терялась бы.
 */
export function averagePercent(...percents: number[]): number {
  const sum = percents.reduce((acc, p) => acc + Math.round(p), 0);
  return Math.round(sum / percents.length);
}
